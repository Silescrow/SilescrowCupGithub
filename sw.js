const OWN = [CODE_CACHE, ASSET_CACHE];
self.addEventListener('install', e => {
  self.skipWaiting();
  e.waitUntil(caches.open(CODE_CACHE).then(c => Promise.all(CODE.map(u => c.add(new Request(u, { cache: 'reload' })).catch(() => {})))));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => !OWN.includes(k)).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
async function warm(){
  const c = await caches.open(ASSET_CACHE);
  const todo = [];
  for (const u of ASSETS) if (!(await c.match(u))) todo.push(u);
  for (let i = 0; i < todo.length; i += 12){
    await Promise.all(todo.slice(i, i + 12).map(u => fetch(u).then(r => { if (r && r.ok) return c.put(u, r); }).catch(() => {})));
  }
}
self.addEventListener('message', e => { if (e.data === 'warm') e.waitUntil(warm()); });
const isAsset = p => /\.(webp|png|mp3|jpg|jpeg|svg|woff2?)$/i.test(p) && /\/(images|audio)\//.test(p);
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (url.searchParams.has('vcheck')) return;               // Versionsprüfung des Spiels immer direkt aus dem Netz
  if (isAsset(url.pathname)){
    e.respondWith(caches.open(ASSET_CACHE).then(async c => {
      const hit = await c.match(req, { ignoreSearch: true });
      if (hit) return hit;
      const r = await fetch(req); if (r && r.ok) c.put(req, r.clone()); return r;
    }));
    return;
  }
  e.respondWith((async () => {
    const c = await caches.open(CODE_CACHE);
    const net = fetch(req).then(r => { if (r && r.ok && r.status === 200) c.put(req.mode === 'navigate' ? url.pathname : req, r.clone()); return r; });
    const timeout = new Promise(res => setTimeout(() => res(null), 4000));
    try {
      const r = await Promise.race([net, timeout]);
      if (r) return r;
    } catch (err) {}
    const hit = await c.match(req, { ignoreSearch: true }) || await c.match(url.pathname, { ignoreSearch: true }) || (req.mode === 'navigate' ? await c.match("Silescrow_Cup_V4_2.html") : null);
    if (hit) return hit;
    return net.catch(() => new Response('Offline', { status: 503 }));
  })());
});
